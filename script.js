const buildReadableTable = (config) => {
  const [leftHeader, rightHeader] = config.headers;
  const rows = config.rows.map(([left, right]) => `
    <tr>
      <td data-label="${leftHeader}">${left}</td>
      <td data-label="${rightHeader}">${right}</td>
    </tr>`).join('');

  return `
    <thead><tr><th>${leftHeader}</th><th>${rightHeader}</th></tr></thead>
    <tbody>${rows}</tbody>`;
};

const applyReadableArticleTable = () => {
  const config = lazinessTableConfigs[articleSlug];
  if (!config) return true;

  const practiceTitle = document.querySelector('#practice-title');
  const practiceSection = practiceTitle?.closest('section');
  const table = config.staticTable
    ? document.querySelector('.article-table')
    : practiceSection?.querySelector('.article-table');

  if (!table) return false;
  if (table.dataset.readableTable === articleSlug) return true;

  if (!config.staticTable && practiceSection) {
    practiceTitle.textContent = config.title;
    const paragraphs = practiceSection.querySelectorAll(':scope > p');
    if (paragraphs[0]) paragraphs[0].textContent = config.intro;
    if (paragraphs[1]) paragraphs[1].textContent = config.note;
    const tocLink = document.querySelector('.article-toc a[href="#practice-title"]');
    if (tocLink) tocLink.textContent = config.title;
  }

  const wrap = table.closest('.table-wrap');
  if (wrap) {
    wrap.classList.add('table-wrap-readable');
    wrap.setAttribute('aria-label', config.aria);
  }

  table.classList.add('article-table-readable');
  table.dataset.readableTable = articleSlug;
  table.innerHTML = buildReadableTable(config);
  return true;
};

if (!applyReadableArticleTable()) {
  const readableTableObserver = new MutationObserver(() => {
    if (applyReadableArticleTable()) readableTableObserver.disconnect();
  });
  const articleRoot = document.querySelector('#content');
  if (articleRoot) readableTableObserver.observe(articleRoot, { childList: true, subtree: true });
}

const loadScript = (src) => new Promise((resolve, reject) => {
  const script = document.createElement('script');
  script.src = src;
  script.onload = resolve;
  script.onerror = reject;
  document.head.append(script);
});

