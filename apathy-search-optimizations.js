  const setMeta = (selector, value) => {
    const el = document.querySelector(selector);
    if (el) el.setAttribute('content', value);
  };

  const apply = () => {
    const h1 = document.querySelector('.article-header h1');
    const lead = document.querySelector('.article-header .article-lead');
    const body = document.querySelector('.article-body');
    if (!h1 || !lead || !body) return false;
    if (body.dataset.searchOptimized === 'true') return true;

    h1.textContent = config.title;
    lead.textContent = config.lead;
    document.title = `${config.title} | Лінь`;
    setMeta('meta[name="description"]', config.meta);
    setMeta('meta[property="og:title"]', config.title);
    setMeta('meta[property="og:description"]', config.meta);

    Object.entries(config.headings || {}).forEach(([from, to]) => {
      body.querySelectorAll('h2').forEach((heading) => {
        if (heading.textContent.trim() === from) heading.textContent = to;
      });
    });

    if (config.summaryTitle && Array.isArray(config.summary) && !body.querySelector('[data-search-summary]')) {
      const section = document.createElement('section');
      section.dataset.searchSummary = '';
      const heading = document.createElement('h2');
      heading.textContent = config.summaryTitle;
      section.append(heading);
      config.summary.forEach((text) => {
        const p = document.createElement('p');
        p.textContent = text;
        section.append(p);
      });
      const cta = body.querySelector('.bot-cta');
      if (cta) cta.after(section);
      else body.prepend(section);
    }

    body.dataset.searchOptimized = 'true';
    return true;
  };

  if (apply()) return;
  const observer = new MutationObserver(() => {
    if (apply()) observer.disconnect();
  });
  observer.observe(document.documentElement, {childList: true, subtree: true});
